/*
Nesse programa vamos estuar a estrutura de repetição
'for'
 */
package aula11c;

public class Aula11c {

    public static void main(String[] args) {
        
        for (int i = 1; i <= 10; i++){
            System.out.println("Contador: " + i);
        }
        System.out.println("=".repeat(40));
        System.out.println("Fim do programa");
    }
    
}
